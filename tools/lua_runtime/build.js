const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const license = ['fengari', 'sprintf-js'].map(name =>
  name + '\n' + fs.readFileSync(require.resolve(name + '/LICENSE'), 'utf8')
).join('\n');
const result = esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'entry.js')],
  bundle: true,
  platform: 'browser',
  format: 'iife',
  globalName: 'WkrlLua',
  target: 'es2017',
  define: { process: 'undefined', 'process.env.FENGARICONF': 'undefined' },
  minify: true,
  write: false,
});
const entry = '\nreturn async function (api) {\n' +
  '  const source = api.args.length ? api.args[0] : "print(1 + 1)";\n' +
  '  await WkrlLua.run(api, source);\n};\n';
const runtime = '// Generated by tools/lua_runtime/build.js; do not edit.\n/*\n' +
  license + '\n*/\n' + result.outputFiles[0].text;
fs.writeFileSync(path.join(root, 'payloads/lua_loader.js'), runtime + entry);
fs.writeFileSync(path.join(root, 'src/lua-vm.js'), runtime +
  '\nexport async function run(api, source, name) { return WkrlLua.run(api, source, name); }\n');
console.log('Built payloads/lua_loader.js and src/lua-vm.js');
