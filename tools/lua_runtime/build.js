const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const license = ['fengari', 'sprintf-js'].map(name =>
  name + '\n' + fs.readFileSync(require.resolve(name + '/LICENSE'), 'utf8')
).join('\n');
async function build() {
  const result = await esbuild.build({
    entryPoints: [path.join(__dirname, 'entry.js')],
    bundle: true,
    loader: { '.lua': 'text' },
    platform: 'browser',
    format: 'iife',
    globalName: 'WkrlLua',
    target: 'es2017',
    define: { process: 'undefined', 'process.env.FENGARICONF': 'undefined' },
    minify: true,
    write: false,
    plugins: [{
      name: 'fengari-local-byte-arrays',
      setup(build) {
        build.onLoad({ filter: /[\\/]fengari[\\/]src[\\/]defs\.js$/ }, args => {
          // Use Fengari's constructor/copy fallbacks so string identity does not
          // depend on potentially replaced static typed-array factories.
          if (require('fengari/package.json').version !== '0.1.4')
            throw Error('Review Fengari byte-array fallback for this version');
          let contents = fs.readFileSync(args.path, 'utf8');
          for (const factory of ['from', 'of']) {
            const original = `if (typeof Uint8Array.${factory} === "function") {`;
            if (!contents.includes(original)) throw Error(`Missing Fengari ${factory} fallback`);
            contents = contents.replace(original, 'if (false) {');
          }
          return { contents, loader: 'js' };
        });
      },
    }],
  });
  const runtime = '// Generated by tools/lua_runtime/build.js; do not edit.\n/*\n' +
    license + '\n*/\n' + result.outputFiles[0].text;
  fs.writeFileSync(path.join(root, 'src/lua-vm.js'), runtime +
    '\nexport async function run(api, source, name) { return WkrlLua.run(api, source, name); }\n');
  console.log('Built src/lua-vm.js');
}
build().catch(error => { console.error(error); process.exitCode = 1; });
